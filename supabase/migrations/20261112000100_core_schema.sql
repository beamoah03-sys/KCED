-- ---------------------------------------------------------------------------
-- Shared trigger: keep updated_at current
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- jurisdictions: the campus areas every record belongs to
-- ---------------------------------------------------------------------------
create table public.jurisdictions (
  id                  integer generated by default as identity primary key,
  name                text not null unique,
  code                text not null unique check (code ~ '^[A-Z0-9-]{2,12}$'),
  sort_order          integer not null default 0,
  -- Technicians in a maintenance-yard area can be assigned work anywhere.
  -- Replaces the hard-coded "jurisdiction 48" from Phase I.
  is_maintenance_yard boolean not null default false,
  created_at          timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- users: one profile row per auth user (id = auth.users.id)
-- ---------------------------------------------------------------------------
create table public.users (
  id              uuid primary key references auth.users (id) on delete cascade,
  email           text not null unique,
  full_name       text,
  phone           text check (phone is null or phone ~ '^\+?[0-9]{9,15}$'),
  avatar_url      text,
  role            public.user_role not null default 'technician',
  status          public.user_status not null default 'invited',
  jurisdiction_id integer references public.jurisdictions (id) on delete set null,
  invited_by      uuid references public.users (id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  -- Everyone except admins works inside one jurisdiction.
  constraint users_jurisdiction_required
    check (role = 'admin' or jurisdiction_id is not null or status = 'invited')
);
create index users_jurisdiction_idx on public.users (jurisdiction_id);
create index users_role_status_idx on public.users (role, status);
create trigger users_updated_at before update on public.users
  for each row execute function public.set_updated_at();


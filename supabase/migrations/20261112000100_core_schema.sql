-- A new auth user (created by the invite-user function) gets a profile row.
-- Role and jurisdiction are NOT read from user metadata, which the user can
-- edit; the invite-user function sets them with the service role.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (id, email, full_name, status)
  values (new.id, new.email, nullif(new.raw_user_meta_data ->> 'full_name', ''), 'invited')
  on conflict (id) do nothing;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_auth_user();

-- Mirror email changes (OTP email-change flow) and the name set during
-- account setup into the profile.
create or replace function public.handle_auth_user_updated()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Tell users_guard() this write comes from the auth service, not the user.
  perform set_config('kced.sync_from_auth', 'on', true);
  update public.users
     set email = new.email,
         full_name = coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), full_name)
   where id = new.id
     and (email is distinct from new.email
          or full_name is distinct from coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), full_name));
  return new;
end;
$$;
create trigger on_auth_user_updated after update of email, raw_user_meta_data on auth.users
  for each row execute function public.handle_auth_user_updated();

-- ---------------------------------------------------------------------------
-- Schedule: mark overdue work orders every 15 minutes (Supabase has pg_cron).
-- Skipped silently where pg_cron is not installed (e.g. plain local Postgres).
-- ---------------------------------------------------------------------------
do $$
begin
  create extension if not exists pg_cron;
  perform cron.schedule('mark-overdue-work-orders', '*/15 * * * *',
                        'select public.mark_overdue_work_orders();');
exception when others then
  raise notice 'pg_cron not available; schedule mark_overdue_work_orders() another way.';
end;
$$;

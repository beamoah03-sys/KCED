-- Human-friendly number, e.g. SR-2026-00042, and basic abuse protection.
create or replace function public.service_requests_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recent integer;
begin
  -- Rate limit: at most 5 requests per phone number per hour.
  select count(*) into recent
  from public.service_requests
  where reporter_contact = new.reporter_contact
    and created_at > now() - interval '1 hour';
  if recent >= 5 then
    raise exception 'Too many requests from this phone number. Please try again later.'
      using errcode = 'P0001';
  end if;

  if new.request_number is null then
    new.request_number := 'SR-' || to_char(now(), 'YYYY') || '-'
      || lpad(nextval('public.service_request_number_seq')::text, 5, '0');
  end if;
  -- Anonymous submitters cannot choose a status.
  if auth.role() is distinct from 'service_role' then
    new.status := 'submitted';
  end if;
  return new;
end;
$$;
create trigger service_requests_before_insert before insert on public.service_requests
  for each row execute function public.service_requests_before_insert();


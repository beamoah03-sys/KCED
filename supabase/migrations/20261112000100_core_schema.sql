-- Fill latitude/longitude from a "lat, lng" location string when the client
-- only sends text (Phase I web + mobile behaviour).
create or replace function public.assets_parse_location()
returns trigger
language plpgsql
as $$
declare
  parts text[];
begin
  if new.location is not null
     and (new.latitude is null or new.longitude is null
          or (tg_op = 'UPDATE' and new.location is distinct from old.location))
     and new.location ~ '^\s*-?\d+(\.\d+)?\s*,\s*-?\d+(\.\d+)?\s*$' then
    parts := regexp_split_to_array(trim(new.location), '\s*,\s*');
    if parts[1]::double precision between -90 and 90
       and parts[2]::double precision between -180 and 180 then
      new.latitude := parts[1]::double precision;
      new.longitude := parts[2]::double precision;
    end if;
  end if;
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  return new;
end;
$$;
create trigger assets_parse_location before insert or update on public.assets
  for each row execute function public.assets_parse_location();


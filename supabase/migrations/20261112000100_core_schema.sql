create or replace function public.log_service_request_activity()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    perform public.log_activity('service_request', new.id::text, 'created',
      coalesce(new.issue, 'Untitled request'), new.request_number, new.jurisdiction_id);
  elsif new.status is distinct from old.status then
    perform public.log_activity('service_request', new.id::text, 'status_changed',
      coalesce(new.issue, 'Untitled request'), new.status::text, new.jurisdiction_id);
  end if;
  return new;
end;
$$;
create trigger service_request_activity after insert or update on public.service_requests
  for each row execute function public.log_service_request_activity();


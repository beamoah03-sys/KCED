create or replace function public.work_orders_before_write()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' and new.work_order_number is null then
    new.work_order_number := 'WO-' || to_char(now(), 'YYYY') || '-'
      || lpad(nextval('public.work_order_number_seq')::text, 5, '0');
  end if;

  -- completed_at follows status, whoever writes it.
  if new.status = 'completed' and new.completed_at is null then
    new.completed_at := now();
  elsif new.status <> 'completed' then
    new.completed_at := null;
  end if;

  -- Overdue is derived from the deadline for orders that have not started.
  if new.status = 'pending' and new.deadline is not null and new.deadline < now() then
    new.status := 'overdue';
  elsif new.status = 'overdue' and (new.deadline is null or new.deadline >= now()) then
    new.status := 'pending';
  end if;
  return new;
end;
$$;
create trigger work_orders_before_write before insert or update on public.work_orders
  for each row execute function public.work_orders_before_write();

-- Called on a schedule (see the cron block at the end of this file): flips
-- pending orders whose deadline has passed to overdue.
create or replace function public.mark_overdue_work_orders()
returns integer
language sql
security definer
set search_path = public
as $$
  with flipped as (
    update public.work_orders
       set status = 'overdue'
     where status = 'pending' and deadline is not null and deadline < now()
    returning 1
  )
  select count(*)::integer from flipped;
$$;

-- Keep the request's status in step with its work order, so staff lists and
-- the public tracker always agree (fixes Phase I bug 5).
create or replace function public.sync_request_status_from_work_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target uuid;
  next_status public.service_request_status;
begin
  if tg_op = 'DELETE' then
    if old.service_request_id is not null then
      update public.service_requests
         set status = 'submitted'
       where id = old.service_request_id and status <> 'cancelled';
    end if;
    return old;
  end if;

  target := new.service_request_id;
  if target is null then
    return new;
  end if;

  next_status := case new.status
    when 'completed' then 'resolved'
    when 'in progress' then 'in progress'
    else 'assigned'
  end::public.service_request_status;

  update public.service_requests
     set status = next_status
   where id = target and status is distinct from next_status and status <> 'cancelled';
  return new;
end;
$$;
create trigger work_orders_sync_request
  after insert or update of status, service_request_id or delete on public.work_orders
  for each row execute function public.sync_request_status_from_work_order();


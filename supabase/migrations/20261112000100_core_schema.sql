-- Rebuilt from what the Phase I web app (KCED-Web) and mobile app
-- (kced_mobile) read and write, so table, column and enum names stay
-- compatible with both clients.
--
-- IMPORTANT for the existing live project: these migrations describe a FRESH
-- database. If you already have the Phase I Supabase project, run
-- `supabase db pull` first and compare (see docs/RUNBOOK.md) instead of
-- applying this file on top of live data.
